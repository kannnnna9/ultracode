#!/usr/bin/env python3
"""Generate references/library-index.md from the vendored packs.

One line per pack: `- <name> — <description>` grouped by category. The index is
what ultra:library reads; it must never drift from disk, so tests regenerate it
and compare.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

CATEGORY_BLURB = {
    "lang": "Languages: idioms, typing, testing, project layout.",
    "web": "Frontend: React/Vue/Angular/Next/Nuxt/Vite, a11y, motion, performance.",
    "backend": "APIs, services, databases, migrations, error handling.",
    "infra": "Containers, orchestration, deployment, observability, MCP, cost.",
    "mobile": "Android, Compose Multiplatform, React Native.",
    "data": "ML engineering, PyTorch, evals, AI regression testing.",
    "security": "Security review, agent hardening, supply chain, recon.",
    "quality": "E2E, test collaboration, benchmarks, desktop E2E.",
    "product": "ADRs, discovery, onboarding, code tours, research.",
    "agent": "Agent engineering, harnesses, loops, orchestration, self-eval.",
}


MAX_DESC = 200


def frontmatter(text: str) -> dict:
    """Flat scalars plus folded/literal block scalars (``>-``, ``|``)."""
    text = re.sub(r"^\s*(?:<!--[\s\S]*?-->\s*)+", "", text)  # tolerate a leading comment
    if not text.startswith("---"):
        return {}
    m = re.search(r"\n---\s*\n", text[3:])
    if not m:
        return {}
    lines = text[3:m.start() + 3].splitlines()
    out, i = {}, 0
    while i < len(lines):
        key, sep, value = lines[i].partition(":")
        key, value = key.strip(), value.strip()
        if sep and re.match(r"^[A-Za-z_][\w-]*$", key):
            if value in (">", ">-", "|", "|-"):
                block = []
                i += 1
                while i < len(lines) and (lines[i].startswith((" ", "\t")) or not lines[i].strip()):
                    block.append(lines[i].strip())
                    i += 1
                out[key] = " ".join(x for x in block if x)
                continue
            out[key] = value.strip("\"'")
        i += 1
    return out


def shorten(desc: str, limit: int = MAX_DESC) -> str:
    desc = re.sub(r"\s+", " ", desc).strip()
    if len(desc) <= limit:
        return desc
    cut = desc[:limit]
    idx = cut.rfind(". ")
    if idx > limit * 0.4:
        return cut[:idx + 1].rstrip()
    idx = cut.rfind(" ")
    return cut[:idx].rstrip(" ,;:-") + "…"


def collect(root: Path):
    rows = []
    base = root / "library"
    if not base.is_dir():
        return rows
    for skill in sorted(base.glob("*/*/SKILL.md")):
        rel = skill.relative_to(base)
        category, name = rel.parts[0], rel.parts[1]
        text = skill.read_text(encoding="utf-8", errors="replace")
        fm = frontmatter(text)
        desc = shorten(fm.get("description", "") or "(no description)")
        rows.append((category, name, desc, len(text)))
    return rows


def render(rows) -> str:
    out = [
        "# Library index",
        "",
        "Generated by `scripts/build_index.py` — do not edit by hand.",
        "Read a pack with `read_file(\"library/<category>/<name>/SKILL.md\")`.",
        "",
    ]
    by_cat = {}
    for category, name, desc, size in rows:
        by_cat.setdefault(category, []).append((name, desc, size))
    for category in sorted(by_cat):
        out.append(f"## {category}/")
        out.append("")
        out.append(CATEGORY_BLURB.get(category, ""))
        out.append("")
        for name, desc, size in by_cat[category]:
            out.append(f"- `{name}` — {desc}")
        out.append("")
    out.append(f"_{len(rows)} packs._")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".", help="repo root")
    ap.add_argument("--check", action="store_true", help="fail if the index is stale")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    rows = collect(root)
    if not rows:
        print("no packs found under library/", file=sys.stderr)
        return 2
    text = render(rows)
    target = root / "references" / "library-index.md"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current.strip() != text.strip():
            print(f"stale index: {target}", file=sys.stderr)
            return 1
        print(f"index ok: {len(rows)} packs")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} ({len(rows)} packs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
