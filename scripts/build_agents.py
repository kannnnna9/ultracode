#!/usr/bin/env python3
"""Generate the repo-root AGENTS.md from the contract (single source of truth)."""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MAINTENANCE = """
## Working on this repo

- `skills/` — the spine, one SKILL.md per skill. Edit here; the plugin and every portable
  install read these files directly.
- `library/` — vendored ECC packs. Never edit by hand: re-vendor with
  `python scripts/vendor_library.py --from <ecc>/skills`, then
  `python scripts/normalize_library.py`, then `python scripts/build_index.py`.
- `references/library-index.md` — generated; `build_index.py --check` must pass.
- `__init__.py` — Hermes plugin: registers the skills, splits the contract into two prompt
  sections, installs the two guard hooks.
- Tests: `python -m unittest discover -s tests` (30 tests, no network).
- Audit: `python scripts/audit.py`; simulation: `python sim/run_sim.py`.
- A rule goes in the contract only if it must hold every turn; otherwise it belongs in a skill.
  When you add a rule, delete the wording it replaces.
"""


def main() -> int:
    text = (ROOT / "skills" / "contract" / "SKILL.md").read_text(encoding="utf-8")
    body = text.split("---", 2)[2].replace("<!-- ultra-section-2 -->", "").strip()
    out = (
        "# AGENTS.md — ULTRACODE\n\n"
        "<!-- generated by scripts/build_agents.py from skills/contract/SKILL.md; edit the contract -->\n\n"
        f"{body}\n{MAINTENANCE}"
    )
    (ROOT / "AGENTS.md").write_text(out, encoding="utf-8")
    print(f"wrote AGENTS.md ({len(out)} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
